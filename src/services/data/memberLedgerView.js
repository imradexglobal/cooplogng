const ALL_MEMBERS = 'All'
const UNALLOCATED_ACCOUNT_ID = '__member_unallocated__'

function amountOf(value) {
  const amount = Number.parseFloat(value)
  return Number.isFinite(amount) ? amount : 0
}

function truthy(value) {
  return value === true || value === 1 || value === '1' || String(value).toLowerCase() === 'true'
}

function dateOf(remittance) {
  const raw = String(remittance?.remittance_date || remittance?.created_at || '')
  const date = raw
    ? new Date(/^\d{4}-\d{2}-\d{2}$/.test(raw) ? `${raw}T00:00:00` : raw)
    : null
  return date && !Number.isNaN(date.getTime()) ? date : null
}

function inPeriod(date, start, end) {
  if (!date) return false
  return date >= start && date <= end
}

function compareChronological(a, b) {
  const dateA = dateOf(a)
  const dateB = dateOf(b)
  const dateCompare = (dateA?.getTime() || 0) - (dateB?.getTime() || 0)
  if (dateCompare !== 0) return dateCompare
  const createdCompare = String(a.created_at || '').localeCompare(String(b.created_at || ''))
  if (createdCompare !== 0) return createdCompare
  return String(a.id || '').localeCompare(String(b.id || ''))
}

export function isInternalTransfer(remittance) {
  return String(remittance?.bank_name || '').trim().toLowerCase() === 'internal transfer' ||
    String(remittance?.transaction_type || '').trim().toLowerCase() === 'internal transfer'
}

export function isAutoDuesCharge(remittance) {
  const isAutoGenerated = truthy(remittance?.autogen)
  return isAutoGenerated && /^auto internal charges\b/i.test(String(remittance?.description || '').trim())
}

/**
 * The generated zero-header settlement moves the charge between member
 * enterprise accounts. Keep its details in account closing balances, but do
 * not show it as another member transaction. The separate negative auto-charge
 * entry remains visible as the member's actual charge.
 */
export function isDuesSettlementNoise(remittance) {
  const isAutoGenerated = truthy(remittance?.autogen)
  return isAutoGenerated && /^auto dues transfer\b/i.test(String(remittance?.description || '').trim())
}

function isMemberDetailIncluded(detail, enterpriseById) {
  const enterpriseId = String(detail?.enterprise_id || detail?.item || '')
  const enterprise = enterpriseById.get(enterpriseId)
  if (!enterprise) return true

  const isRevenue = truthy(enterprise.revenue)
  const isDueOrPenalty = truthy(enterprise.compulsory_due) || truthy(enterprise.is_penalty)
  // Match buildAccountBalance: pure revenue does not increase member net worth,
  // while compulsory dues and penalties remain member obligations.
  return !(isRevenue && !isDueOrPenalty)
}

function memberDetailMovement(remittance, enterpriseById) {
  const details = Array.isArray(remittance?.details) ? remittance.details : []
  if (details.length === 0) {
    const amount = amountOf(remittance?.amount)
    return { credit: Math.max(amount, 0), debit: Math.max(-amount, 0), net: amount, hasDetails: false }
  }

  let credit = 0
  let debit = 0
  for (const detail of details) {
    if (!isMemberDetailIncluded(detail, enterpriseById)) continue
    const amount = amountOf(detail.amount)
    if (amount > 0) credit += amount
    else if (amount < 0) debit += Math.abs(amount)
  }
  return { credit, debit, net: credit - debit, hasDetails: true }
}

function addToAccount(accounts, id, name, amount, isOpening) {
  if (!accounts.has(id)) accounts.set(id, { id, name, opening: 0, periodNet: 0, closing: 0 })
  const account = accounts.get(id)
  if (isOpening) account.opening += amount
  else account.periodNet += amount
}

function buildMemberAccountBalances(remittances, enterprises, memberId, start, end) {
  const enterpriseById = new Map((enterprises || []).map((enterprise) => [String(enterprise.id), enterprise]))
  const accounts = new Map()
  const memberRows = remittances
    .filter((remittance) => remittance.status === 'Approved' && String(remittance.member_id) === memberId)
    .sort(compareChronological)

  for (const remittance of memberRows) {
    const date = dateOf(remittance)
    if (!date || date > end) continue
    const isOpening = date < start
    const details = Array.isArray(remittance.details) ? remittance.details : []

    if (details.length === 0) {
      const amount = amountOf(remittance.amount)
      if (amount !== 0) {
        addToAccount(accounts, UNALLOCATED_ACCOUNT_ID, 'Unallocated member activity', amount, isOpening)
      }
      continue
    }

    for (const detail of details) {
      if (!isMemberDetailIncluded(detail, enterpriseById)) continue
      const amount = amountOf(detail.amount)
      if (amount === 0) continue
      const id = String(detail.enterprise_id || detail.item || UNALLOCATED_ACCOUNT_ID)
      const name = enterpriseById.get(id)?.account_name || 'Unknown account'
      addToAccount(accounts, id, name, amount, isOpening)
    }
  }

  for (const account of accounts.values()) {
    account.closing = account.opening + account.periodNet
  }
  return [...accounts.values()].sort((a, b) => a.name.localeCompare(b.name))
}

function buildEnterpriseBalances(remittances, enterprises, start, end) {
  const enterpriseById = new Map((enterprises || []).map((enterprise) => [String(enterprise.id), enterprise]))
  const accounts = new Map()
  const approved = remittances.filter((remittance) => remittance.status === 'Approved')
  for (const remittance of approved) {
    const date = dateOf(remittance)
    if (!date || date > end) continue
    const details = Array.isArray(remittance.details) ? remittance.details : []
    for (const detail of details) {
      if (!isMemberDetailIncluded(detail, enterpriseById)) continue
      const amount = amountOf(detail.amount)
      if (amount === 0) continue
      const id = String(detail.enterprise_id || detail.item || UNALLOCATED_ACCOUNT_ID)
      const name = enterpriseById.get(id)?.account_name || 'Unknown account'
      if (!accounts.has(id)) accounts.set(id, { id, name, opening: 0, periodNet: 0, closing: 0 })
      const account = accounts.get(id)
      if (date < start) account.opening += amount
      else if (inPeriod(date, start, end)) account.periodNet += amount
    }
  }
  for (const account of accounts.values()) account.closing = account.opening + account.periodNet
  return [...accounts.values()].sort((a, b) => a.name.localeCompare(b.name))
}

function buildBankBalances(remittances, start, end) {
  const banks = new Map()
  for (const remittance of remittances) {
    const bankName = String(remittance.bank_name || '').trim()
    if (!bankName) continue
    const key = bankName.toLowerCase()
    if (!banks.has(key)) banks.set(key, { id: key, name: bankName, opening: 0, credit: 0, debit: 0, closing: 0 })
    const bank = banks.get(key)
    const date = dateOf(remittance)
    if (!date || date > end) continue
    const amount = amountOf(remittance.amount)
    if (date < start) bank.opening += amount
    else if (inPeriod(date, start, end)) {
      if (amount > 0) bank.credit += amount
      else if (amount < 0) bank.debit += Math.abs(amount)
    }
  }
  for (const bank of banks.values()) bank.closing = bank.opening + bank.credit - bank.debit
  return [...banks.values()].sort((a, b) => a.name.localeCompare(b.name))
}

/**
 * Build the posted activity shown by the active Member Ledger screen.
 * Global scope is a cash/bank view based on remittance headers; selected-member
 * scope is a net-worth view based on the member's allocated details.
 */
export function buildMemberLedgerView({ remittances = [], enterprises = [], memberId = ALL_MEMBERS, start, end }) {
  const selectedMemberId = String(memberId || ALL_MEMBERS)
  const isMemberScope = selectedMemberId !== ALL_MEMBERS
  const enterpriseById = new Map((enterprises || []).map((enterprise) => [String(enterprise.id), enterprise]))

  const approved = remittances.filter((remittance) => remittance.status === 'Approved')
  const scopedRemittances = isMemberScope
    ? approved.filter((remittance) =>
        String(remittance.member_id) === selectedMemberId && !isDuesSettlementNoise(remittance)
      )
    : approved.filter((remittance) => {
        const bankName = String(remittance.bank_name || '').trim()
        return bankName !== '' && !isInternalTransfer(remittance)
      })

  const ordered = [...scopedRemittances].sort(compareChronological)
  let opening = 0
  for (const remittance of ordered) {
    const date = dateOf(remittance)
    if (!date || date >= start || date > end) continue
    opening += isMemberScope
      ? memberDetailMovement(remittance, enterpriseById).net
      : amountOf(remittance.amount)
  }

  let balance = opening
  let credits = 0
  let debits = 0
  const periodRows = []
  const paymentCreditsByMonth = new Array(12).fill(0)

  for (const remittance of ordered) {
    const date = dateOf(remittance)
    if (!date) continue

    // Monthly paid indicators represent positive real bank/method receipts,
    // not zero-net internal reallocations or the dues settlement children.
    const amount = amountOf(remittance.amount)
    const fiscalMonthOffset = (date.getFullYear() - start.getFullYear()) * 12 +
      date.getMonth() - start.getMonth()
    if (!isInternalTransfer(remittance) && amount > 0 && fiscalMonthOffset >= 0 && fiscalMonthOffset < 12) {
      paymentCreditsByMonth[fiscalMonthOffset] += amount
    }

    if (!inPeriod(date, start, end)) continue

    let credit
    let debit
    let balanceImpact
    if (!isMemberScope) {
      credit = Math.max(amount, 0)
      debit = Math.max(-amount, 0)
      balanceImpact = amount
    } else if (isInternalTransfer(remittance)) {
      const movement = memberDetailMovement(remittance, enterpriseById)
      credit = movement.credit
      debit = movement.debit
      balanceImpact = movement.net
    } else {
      // Show the actual bank payment in the activity columns. The running
      // member balance follows allocated member-account details, excluding
      // pure revenue but retaining compulsory dues and penalties.
      const movement = memberDetailMovement(remittance, enterpriseById)
      credit = Math.max(amount, 0)
      debit = Math.max(-amount, 0)
      balanceImpact = movement.net
    }

    balance += balanceImpact
    credits += credit
    debits += debit
    periodRows.push({
      remittance,
      date,
      credit,
      debit,
      balanceImpact,
      balanceAfter: balance,
      isInternalTransfer: isInternalTransfer(remittance),
      isAutoDuesCharge: isAutoDuesCharge(remittance),
    })
  }

  const bankBalances = isMemberScope ? [] : buildBankBalances(scopedRemittances, start, end)
  const enterpriseBalances = isMemberScope
    ? []
    : buildEnterpriseBalances(approved, enterprises, start, end)
  const memberAccountBalances = isMemberScope
    ? buildMemberAccountBalances(approved, enterprises, selectedMemberId, start, end)
    : []

  return {
    isMemberScope,
    scopedRemittances,
    periodRows,
    opening,
    credits,
    debits,
    closing: balance,
    bankBalances,
    enterpriseBalances,
    memberAccountBalances,
    paymentCreditsByMonth,
  }
}
